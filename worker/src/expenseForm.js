import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { isoDate } from "./procore-directcost.js";

// The Einbau "Employee Expense Form", drawn by TALLY. The original is a Procore Forms PDF; every
// expense in TALLY now carries one, filled in from the lines the submitter built and Claude read.
//
// Same rules as the original form:
//  - the category columns hold the GROSS amount (tax included, the total of the receipt) as entered; the
//    form does no calculating of its own;
//  - "Net Total" is the one thing it adds: TALLY's net per category (read off the receipts and checked by
//    the submitter and the approvers), which is the number that posts to Procore;
//  - Authorized By / Date Authorized are filled when the expense is approved.

export const GENERATED_FORM_NOTE = "Form generated by TALLY";

const PROVINCES = {
  AB: "Alberta", BC: "British Columbia", MB: "Manitoba", NB: "New Brunswick", NL: "Newfoundland and Labrador",
  NS: "Nova Scotia", NT: "Northwest Territories", NU: "Nunavut", ON: "Ontario", PE: "Prince Edward Island",
  QC: "Quebec", SK: "Saskatchewan", YT: "Yukon",
};

// The six amount columns, in the form's order. Mileage is kilometres, not dollars.
const COLS = [
  { key: "parking", head: "Parking $" },
  { key: "materials", head: "Materials $" },
  { key: "fuel", head: "Fuel $" },
  { key: "mileage", head: "Mileage (KM)", plain: true },
  { key: "per_diem", head: "Per Diem $" },
  { key: "other", head: "Other $" },
];

const safe = (s) =>
  String(s ?? "")
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replace(/[–—]/g, "-").replace(/[“”]/g, '"').replace(/[‘’]/g, "'")
    .replace(/[^\x20-\x7E]/g, "?");

// Toronto's calendar date for an instant, as YYYY-MM-DD (the form's "Date" is the day it is made).
export function torontoDate(d = new Date()) {
  return new Intl.DateTimeFormat("en-CA", { timeZone: "America/Toronto", year: "numeric", month: "2-digit", day: "2-digit" }).format(d);
}

// The form's Expense ID: DDMMYY of the form's date, the LAST 6 DIGITS of the project number (2026_0183 ->
// 260183, 0000_0000_5 -> 000005), and the first two letters of the first name plus the first two of the last
// name (Dustin MacDougall -> DUMA, Scott Carter-Nichols -> SCCA). Matches the IDs the Procore form makes.
export function expenseIdFor({ date, projectNumber, employeeName }) {
  const [y, m, d] = String(isoDate(date) || torontoDate()).split("-");
  const digits = String(projectNumber || "").replace(/\D/g, "");
  const job = digits.slice(-6).padStart(6, "0");
  const tokens = safe(employeeName).toUpperCase().replace(/[^A-Z\s-]/g, "").split(/\s+/).filter(Boolean);
  const first = tokens[0] || "";
  const last = tokens.length > 1 ? tokens[tokens.length - 1] : ""; // "Carter-Nichols" is one surname: CA
  const who = (first.slice(0, 2) + last.slice(0, 2)).padEnd(4, "X");
  return `${d}${m}${String(y).slice(-2)}-${job}-${who}`;
}

const money = (n) => `$ ${Number(n || 0).toFixed(2)}`;
const plain = (n) => Number(n || 0).toFixed(2);

function wrap(text, font, size, maxWidth) {
  const out = [];
  for (const para of safe(text).split("\n")) {
    let line = "";
    for (const word of para.split(/\s+/).filter(Boolean)) {
      const trial = line ? `${line} ${word}` : word;
      if (font.widthOfTextAtSize(trial, size) <= maxWidth) { line = trial; continue; }
      if (line) out.push(line);
      let chunk = "";
      for (const ch of word) {
        if (font.widthOfTextAtSize(chunk + ch, size) > maxWidth) { out.push(chunk); chunk = ch; } else chunk += ch;
      }
      line = chunk;
    }
    out.push(line);
  }
  return out.length ? out : [""];
}

// sub: the submissions row; lines: its line_items rows (gross_amount, net_amount, category, line_date, description)
// authorizedBy / authorizedDate: filled at approval, blank before.
export async function buildExpenseFormPdf({ sub, lines, authorizedBy = null, authorizedDate = null, formDate = null }) {
  const W = 792, H = 612, M = 36;
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const INK = rgb(0.1, 0.1, 0.1), MUTED = rgb(0.42, 0.42, 0.42), RULE = rgb(0.75, 0.75, 0.75);
  const HEAD = rgb(0.93, 0.93, 0.93), ORANGE = rgb(0.886, 0.529, 0.102);

  let page = doc.addPage([W, H]);
  const text = (t, x, y, { size = 9, f = font, color = INK } = {}) => page.drawText(safe(t), { x, y, size, font: f, color });
  const right = (t, xRight, y, opts = {}) => {
    const f = opts.f || font, size = opts.size || 9;
    text(t, xRight - f.widthOfTextAtSize(safe(t), size), y, opts);
  };

  // ---- header
  page.drawRectangle({ x: 0, y: H - 6, width: W, height: 6, color: ORANGE });
  text("Employee Expense Form", M, H - 40, { size: 18, f: bold });
  text("Prepared in TALLY from the receipts", M, H - 54, { size: 8, color: MUTED });
  const prov = String(sub.province || "").toUpperCase();
  const dateShown = isoDate(formDate) || torontoDate();
  const fields = [
    ["Name:", sub.employee_name || ""],
    ["Date:", dateShown],
    ["Project Number:", sub.project_number || ""],
    ["Select Province/Territory:", PROVINCES[prov] || prov],
    ["Expense ID:", sub.expense_id || ""],
  ];
  fields.forEach(([k, v], i) => {
    const y = H - 30 - i * 14;
    right(k, W - M - 190, y, { size: 9, f: bold });
    text(v, W - M - 180, y, { size: 9 });
  });

  // ---- table
  const dateW = 58, descW = 236, colW = 68;
  const tableW = dateW + descW + colW * COLS.length;
  const x0 = M;
  const colX = (i) => x0 + dateW + descW + colW * i;
  let y = H - 118;
  text("Expense Report", x0, y + 8, { size: 11, f: bold });
  y -= 8;

  const drawHead = () => {
    page.drawRectangle({ x: x0, y: y - 16, width: tableW, height: 18, color: HEAD });
    text("Date", x0 + 4, y - 11, { size: 8, f: bold });
    text("Description", x0 + dateW + 4, y - 11, { size: 8, f: bold });
    COLS.forEach((c, i) => right(c.head, colX(i) + colW - 4, y - 11, { size: 8, f: bold }));
    y -= 20;
  };
  drawHead();

  const gross = Object.fromEntries(COLS.map((c) => [c.key, 0]));
  const net = Object.fromEntries(COLS.map((c) => [c.key, 0]));
  const known = new Set(COLS.map((c) => c.key));
  for (const l of lines) {
    const key = known.has(l.category) ? l.category : "other";
    const g = Number(l.gross_amount) || 0;
    const n = Number(l.net_amount) || 0;
    gross[key] += g;
    net[key] += n;
    const desc = wrap(l.description || "", font, 8, descW - 8);
    const rowH = desc.length * 10 + 6;
    if (y - rowH < M + 120) {
      page = doc.addPage([W, H]);
      y = H - M;
      drawHead();
    }
    text(isoDate(l.line_date), x0 + 4, y - 9, { size: 8 });
    desc.forEach((ln, i) => text(ln, x0 + dateW + 4, y - 9 - i * 10, { size: 8 }));
    const ci = COLS.findIndex((c) => c.key === key);
    right(COLS[ci].plain ? plain(g) : money(g), colX(ci) + colW - 4, y - 9, { size: 8 });
    page.drawLine({ start: { x: x0, y: y - rowH + 2 }, end: { x: x0 + tableW, y: y - rowH + 2 }, thickness: 0.4, color: RULE });
    y -= rowH;
  }

  // ---- For Office Use Only: Subtotal (gross), Net Total (TALLY's net), Expense Total
  if (y < M + 120) { page = doc.addPage([W, H]); y = H - M; }
  y -= 6;
  const totalRow = (label, values, bolded) => {
    page.drawRectangle({ x: x0, y: y - 15, width: tableW, height: 17, color: HEAD });
    text(label, x0 + dateW + 4, y - 10, { size: 8.5, f: bold });
    COLS.forEach((c, i) => right(c.plain ? plain(values[c.key]) : money(values[c.key]), colX(i) + colW - 4, y - 10, { size: 8.5, f: bolded ? bold : font }));
    y -= 19;
  };
  text("For Office Use Only", x0 + 4, y - 4, { size: 7.5, color: MUTED });
  y -= 6;
  totalRow("Subtotal:", gross, false);
  totalRow("Net Total:", net, false);
  const grossTotal = COLS.reduce((a, c) => a + (c.plain ? 0 : gross[c.key]), 0);
  y -= 2;
  right("Expense Total:", colX(COLS.length - 1) - 40, y - 8, { size: 10, f: bold });
  right(money(grossTotal), colX(COLS.length - 1) + colW - 4, y - 8, { size: 10, f: bold });
  y -= 30;

  // ---- notes + authorization
  text("Notes:", x0 + 4, y, { size: 9, f: bold });
  const notes = [
    "Amounts in the category columns are gross (tax included), as on the receipts.",
    "Net Total is the pre-tax amount posted to Procore, read from the receipts and reviewed in TALLY.",
  ];
  notes.forEach((n, i) => text(n, x0 + 4, y - 12 - i * 11, { size: 8, color: MUTED }));
  right("Authorized By:", W - M - 190, y, { size: 9, f: bold });
  text(authorizedBy || "", W - M - 180, y, { size: 9 });
  right("Date Authorized:", W - M - 190, y - 16, { size: 9, f: bold });
  text(authorizedDate ? isoDate(authorizedDate) : "", W - M - 180, y - 16, { size: 9 });

  return doc.save();
}

// ---------------------------------------------------------------------------
// The REAL form, filled in. The blank Einbau Employee Expense Form is a fillable PDF (Procore Forms), kept in R2 at
// TEMPLATE_KEY (source copy: worker/assets/employee-expense-form-template.pdf). TALLY fills its fields, so the result
// looks exactly like a form the submitter filled in themselves. buildExpenseFormPdf above (a look-alike drawn from
// scratch) is only the fallback when the template can't be read.
// ---------------------------------------------------------------------------

export const TEMPLATE_KEY = "templates/employee-expense-form.pdf";
const FORM_ROWS = 11; // the form has eleven line rows; more lines go on further copies of the form

// the form's category columns -> its field names
const FORM_COLS = [
  { key: "parking", value: "Parking Value", sub: "ParkingSubtotal", net: "ParkingNetTotal" },
  { key: "materials", value: "Materials Value", sub: "MaterialsSubtotal", net: "Materials Net Total" },
  { key: "fuel", value: "Fuel Value", sub: "FuelSubtotal", net: "Fuel Net Total" },
  { key: "mileage", value: "Mileage Value", sub: "MileageSubtotal", net: "Mileage Net Total", plain: true },
  { key: "per_diem", value: "Per Diem Value", sub: "PerDiemSubtotal", net: "Per Diem Net Total" },
  { key: "other", value: "Other Value", sub: "OtherSubtotal", net: "Other Net Total" },
];

// M/D/YY, the way the form shows dates
export function mdy(v) {
  const iso = isoDate(v);
  if (!iso) return "";
  const [y, m, d] = iso.split("-");
  return `${Number(m)}/${Number(d)}/${y.slice(2)}`;
}
const dollars = (n) => `$ ${Number(n || 0).toFixed(2)}`;

// templateBytes: the blank form. Returns the filled form as PDF bytes (one page per 11 lines, flattened, so it
// looks the same in any viewer and the numbers can't be edited by accident).
export async function buildFormFromTemplate({ templateBytes, sub, lines, authorizedBy = null, authorizedDate = null, formDate = null }) {
  const ordered = [...lines].sort((a, b) => (a.row_index ?? 0) - (b.row_index ?? 0));
  const chunks = [];
  for (let i = 0; i < ordered.length; i += FORM_ROWS) chunks.push(ordered.slice(i, i + FORM_ROWS));
  if (!chunks.length) chunks.push([]);

  const out = await PDFDocument.create();
  const outFont = await out.embedFont(StandardFonts.Helvetica);
  const known = new Set(FORM_COLS.map((c) => c.key));
  const grand = { gross: 0, net: 0 };
  const prov = String(sub.province || "").toUpperCase();
  const provinceName = prov === "PE" ? "PEI" : PROVINCES[prov] || "";

  for (let page = 0; page < chunks.length; page++) {
    const doc = await PDFDocument.load(templateBytes, { ignoreEncryption: true });
    const font = await doc.embedFont(StandardFonts.Helvetica);
    const form = doc.getForm();
    // an explicit type size on every field: left on auto, the form shrinks short values to a speck
    const set = (name, value, size = 8) => {
      const tf = form.getTextField(name);
      tf.acroField.setDefaultAppearance(`/Helv ${size} Tf 0 g`);
      tf.setText(String(value ?? ""));
    };

    set("UserName", safe(sub.employee_name || ""));
    set("Date", mdy(formDate) || mdy(torontoDate()));
    set("JobNumber", safe(sub.project_number || ""));
    set("AutoID", safe(sub.expense_id || ""));
    const dd = form.getDropdown("Dropdown17");
    if (provinceName && dd.getOptions().includes(provinceName)) dd.select(provinceName);
    if (authorizedDate) set("Date Authorized", mdy(authorizedDate));

    const gross = Object.fromEntries(FORM_COLS.map((c) => [c.key, 0]));
    const net = Object.fromEntries(FORM_COLS.map((c) => [c.key, 0]));
    chunks[page].forEach((l, i) => {
      const r = i + 1;
      const key = known.has(l.category) ? l.category : "other";
      const col = FORM_COLS.find((c) => c.key === key);
      const g = Number(l.gross_amount) || 0;
      gross[key] += g;
      net[key] += Number(l.net_amount) || 0;
      set(`Date ${r}`, mdy(l.line_date), 7.5);
      // the description box is one line, 198 pt wide: shrink the type a little, then cut it with an ellipsis
      const desc = form.getTextField(`Description ${r}`);
      let text = safe(l.description || "");
      let size = 7;
      while (size > 5.5 && font.widthOfTextAtSize(text, size) > 192) size -= 0.5;
      while (text.length > 1 && font.widthOfTextAtSize(text, size) > 192) text = text.slice(0, -1);
      if (text !== safe(l.description || "")) text = text.slice(0, -1) + "…";
      desc.acroField.setDefaultAppearance(`/Helv ${size} Tf 0 g`); // these boxes have no default appearance of their own
      desc.setText(text.replace(/…/g, "..."));
      set(`${col.value} ${r}`, col.plain ? Number(g).toFixed(2) : dollars(g), 7.5);
    });
    for (const c of FORM_COLS) {
      set(c.sub, c.plain ? gross[c.key].toFixed(2) : dollars(gross[c.key]), 7.5);
      set(c.net, c.plain ? net[c.key].toFixed(2) : dollars(net[c.key]), 7.5);
    }
    const pageGross = FORM_COLS.reduce((a, c) => a + (c.plain ? 0 : gross[c.key]), 0);
    const pageNet = FORM_COLS.reduce((a, c) => a + (c.plain ? 0 : net[c.key]), 0);
    grand.gross += pageGross;
    grand.net += pageNet;
    set("Expense Total", dollars(pageGross), 8.5);

    // Authorized By is a signature field: it can't hold text, so write the name where it sits
    const sig = form.getSignature("Signature13");
    const rect = sig.acroField.getWidgets()[0].getRectangle();
    form.removeField(sig);
    form.updateFieldAppearances(font);
    form.flatten();
    const p = doc.getPage(0);
    if (authorizedBy) p.drawText(safe(authorizedBy), { x: rect.x + 3, y: rect.y + 2, size: 8, font, color: rgb(0, 0, 0) });

    const [copied] = await out.copyPages(doc, [0]);
    out.addPage(copied);
  }

  if (chunks.length > 1) {
    out.getPages().forEach((p, i) => {
      const label = `Page ${i + 1} of ${chunks.length}. Each page totals its own lines.`;
      p.drawText(label, { x: 54, y: 24, size: 8, font: outFont, color: rgb(0.35, 0.35, 0.35) });
      if (i === chunks.length - 1) {
        p.drawText(`All ${chunks.length} pages: ${dollars(grand.gross)} gross, ${dollars(grand.net)} net`, { x: 54, y: 13, size: 8, font: outFont, color: rgb(0.35, 0.35, 0.35) });
      }
    });
  }
  return out.save();
}
